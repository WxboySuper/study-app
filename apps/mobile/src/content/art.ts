/** The art of an entry. */
export interface ResolvedArt {
  /** The image to show: the PNG of the entry or the placeholder of its type. */
  source: ImageSourcePropType;
  /** The type of the entry the art belongs to. */
  type: ArtType;
  /** `true` when the placeholder is shown instead of the PNG. */
  placeholder: boolean;
}

/** The type of the content an art key belongs to. */
export function artTypeOf(assetId: string): ArtType {
  return contentTypeOf(assetId);
}

/** The image of an art key, or `null` when the art does not exist (yet). */
export function artFor(assetId: string): ImageSourcePropType | null {
  return CONTENT_ART[assetId] ?? null;
}

/** The placeholder image of a type. */
export function placeholderFor(type: ArtType): ImageSourcePropType {
  return PLACEHOLDERS[type];
}

/**
 * The art of an art key.
 *
 * The PNG of the entry is used when it exists; otherwise the placeholder of
 * the type of the entry is shown, so nothing ever renders an empty hole.
 */
export function resolveArt(assetId: string, type?: ArtType): ResolvedArt {
  const artType = type ?? artTypeOf(assetId);
  const source = artFor(assetId);

  if (source !== null) {
    return { source, type: artType, placeholder: false };
  }

  return { source: placeholderFor(artType), type: artType, placeholder: true };
}
