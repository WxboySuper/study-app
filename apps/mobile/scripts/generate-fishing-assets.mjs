#!/usr/bin/env node
/**
 * Refreshes the art map of the app.
 *
 * The PNGs of the game live in `apps/mobile/assets/fishing/` (the scene and
 * the UI), `apps/mobile/assets/critters/` (the critters) and
 * `apps/mobile/assets/content/` (the placeholders). Metro can only bundle a
 * file that exists, so the `require()` calls have to be generated: this
 * script writes the block between the GENERATED ART markers of
 * `src/content/art.ts`.
 *
 * ```bash
 * node scripts/generate-fishing-assets.mjs
 * ```
 *
 * Every art key that is missing simply keeps its placeholder (the mascot of
 * its type), so the game runs without any art.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const appDir = join(here, '..');
const target = join(appDir, 'src', 'content', 'art.ts');

const BEGIN = '// --- BEGIN GENERATED ART ---';
const END = '// --- END GENERATED ART ---';

/** The folders the art comes from (the placeholders are static). */
const FOLDERS = ['fishing', 'critters'];

/**
 * Every PNG of the folders, sorted by id.
 */
function collect() {
  const entries = [];

  for (const folder of FOLDERS) {
    let files;
    try {
      files = readdirSync(join(appDir, 'assets', folder)).filter((name) => name.endsWith('.png')).sort();
    } catch {
      console.error(`No asset folder at assets/${folder}; skipping it.`);
      continue;
    }

    for (const file of files) {
      const id = file.replace(/\.png$/, '');
      entries.push({ id, path: `../../assets/${folder}/${file}` });
    }
  }

  return entries.sort((left, right) => left.id.localeCompare(right.id));
}

const entries = collect();

const map = entries.map((entry) => `  ${entry.id}: require('${entry.path}'),`);

const block = [
  BEGIN,
  '/**',
  ' * The images that exist in `assets/`.',
  ' *',
  ' * Generated by `scripts/generate-fishing-assets.mjs`; every art key that is',
  ' * not listed here falls back to the placeholder of its type.',
  ' */',
  'export const CONTENT_ART: Readonly<Record<string, ImageSourcePropType>> = {',
  ...map,
  '};',
  END,
].join('\n');

const source = readFileSync(target, 'utf8');
const begin = source.indexOf(BEGIN);
const end = source.indexOf(END);

if (begin === -1 || end === -1) {
  console.error('The GENERATED ART markers are missing from art.ts.');
  process.exit(1);
}

const next = `${source.slice(0, begin)}${block}${source.slice(end + END.length)}`;
writeFileSync(target, next, 'utf8');

console.log(`Wrote ${entries.length} image(s) to art.ts.`);
