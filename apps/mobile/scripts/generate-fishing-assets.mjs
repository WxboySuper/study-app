#!/usr/bin/env node
/**
 * Refreshes the sprite map of the fishing mode.
 *
 * The PNGs of the mode live in `apps/mobile/assets/fishing/<asset_id>.png`
 * (see `docs/design/fishing.md` §13a). Metro can only bundle a file that
 * exists, so the `require()` calls have to be generated: this script writes
 * the block between the GENERATED SPRITES markers of `src/modes/fishing/assets.ts`.
 *
 * ```bash
 * node scripts/generate-fishing-assets.mjs
 * ```
 *
 * Every sprite that is missing simply keeps its placeholder (a coloured
 * circle with an emoji), so the game runs without any art.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const assetsDir = join(here, '..', 'assets', 'fishing');
const target = join(here, '..', 'src', 'modes', 'fishing', 'assets.ts');

const BEGIN = '// --- BEGIN GENERATED SPRITES ---';
const END = '// --- END GENERATED SPRITES ---';

let files = [];
try {
  files = readdirSync(assetsDir).filter((name) => name.endsWith('.png')).sort();
} catch {
  console.error(`No asset folder at ${assetsDir}; nothing to generate.`);
  process.exit(0);
}

/**
 * A safe identifier for an asset file ("bg_lake_day" -> "bgLakeDay").
 */
function identifier(fileName) {
  const parts = fileName.replace(/\.png$/, '').split(/[^a-zA-Z0-9]+/).filter(Boolean);
  const name = parts
    .map((part, index) => (index === 0 ? part.toLowerCase() : part.charAt(0).toUpperCase() + part.slice(1).toLowerCase()))
    .join('');
  return `asset${name.charAt(0).toUpperCase()}${name.slice(1)}`;
}

const entries = files.map((name) => {
  const id = name.replace(/\.png$/, '');
  return { id, name, variable: identifier(name) };
});

const imports = entries.map(
  (entry) => `import ${entry.variable} from '../../assets/fishing/${entry.name}';`,
);

const map = entries.map((entry) => `  '${entry.id}': ${entry.variable},`);

const block = [
  BEGIN,
  ...imports,
  '/**',
  ' * The sprites that exist in `assets/fishing`.',
  ' *',
  ' * Generated by `scripts/generate-fishing-assets.mjs`; every id that is not',
  ' * listed here falls back to a coloured circle with an emoji.',
  ' */',
  'export const FISHING_SPRITES: Partial<Record<FishingAssetId, ImageSourcePropType>> = {',
  ...map,
  '};',
  END,
].join('\n');

const source = readFileSync(target, 'utf8');
const begin = source.indexOf(BEGIN);
const end = source.indexOf(END);

if (begin === -1 || end === -1) {
  console.error('The GENERATED SPRITES markers are missing from assets.ts.');
  process.exit(1);
}

const next = `${source.slice(0, begin)}${block}${source.slice(end + END.length)}`;
writeFileSync(target, next, 'utf8');

console.log(`Wrote ${entries.length} sprite(s) to assets.ts.`);
