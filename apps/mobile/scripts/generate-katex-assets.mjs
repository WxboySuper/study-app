#!/usr/bin/env node
/**
 * The KaTeX assets of the app.
 *
 * The math of a question is rendered with KaTeX, and KaTeX has to be there
 * **offline**: the game is played on a phone, in the middle of nowhere, with
 * no network.
 *
 * This script builds the module that carries the KaTeX stylesheet with its
 * fonts inlined (as `data:` URLs), so the app never has to fetch anything.
 * The phone shows the math in a `WebView` that gets the stylesheet inlined;
 * the browser gets the same stylesheet in its `<head>`.
 *
 * ```
 * node apps/mobile/scripts/generate-katex-assets.mjs
 * ```
 *
 * The generated file is committed: the app builds without this script.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const mobileDir = resolve(here, '..');
const katexDir = resolve(mobileDir, '..', '..', 'node_modules', 'katex', 'dist');
const outFile = join(mobileDir, 'src', 'math', 'katexAssets.ts');

/**
 * The fonts of KaTeX, inlined in the stylesheet.
 *
 * Only the `woff2` files are kept: every browser of the last years reads
 * them, and the `woff` and `ttf` files would double the size of the app.
 */
const FONT_PATTERN =
  /src:url\(fonts\/([^)]+\.woff2)\)\s*format\("woff2"\),url\(fonts\/[^)]+\.woff\)\s*format\("woff"\),url\(fonts\/[^)]+\.ttf\)\s*format\("truetype"\)/g;

async function main() {
  const css = await readFile(join(katexDir, 'katex.min.css'), 'utf8');

  // The fonts are read first: the stylesheet is rewritten in one pass.
  const fonts = new Map();
  for (const match of css.matchAll(FONT_PATTERN)) {
    const name = match[1];
    if (name === undefined || fonts.has(name)) {
      continue;
    }
    const bytes = await readFile(join(katexDir, 'fonts', name));
    fonts.set(name, bytes.toString('base64'));
  }

  let inlined = 0;
  const finalCss = css.replace(FONT_PATTERN, (_match, name) => {
    inlined += 1;
    return `src:url(data:font/woff2;base64,${fonts.get(name) ?? ''}) format("woff2")`;
  });

  const header = `/**
 * The KaTeX assets of the app (generated).
 *
 * Do not edit this file: run \`node apps/mobile/scripts/generate-katex-assets.mjs\`
 * to build it again. The stylesheet carries the fonts of KaTeX inlined, so
 * the math renders without a network.
 */

/** The stylesheet of KaTeX, with its fonts inlined. */
export const KATEX_CSS = ${JSON.stringify(finalCss)};
`;

  await writeFile(outFile, header, 'utf8');

  console.log(
    `› ${outFile} (${inlined} fonts, ${Math.round(finalCss.length / 1024)} kB of CSS)`,
  );
}

await main();
